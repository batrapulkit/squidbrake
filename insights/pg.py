"""
Postgres (your Supabase project) for the insights app, behind the same calls the code makes on SQLite: `with db() as
c: c.execute("... WHERE code=?", (code,))`, rows by index or by name, `dict(row)`.

Set INSIGHTS_DATABASE_URL to Supabase's **Session pooler** connection string (Project > Connect; port 5432, works over IPv4).
Tables live in their own schema (INSIGHTS_PG_SCHEMA, default `squidbrake`), which Supabase's public API doesn't
serve, and row level security is on for every one of them, so the anon key on the sign-up page can't reach them.
"""
from __future__ import annotations

import re
from decimal import Decimal


# the tables the code writes with INSERT OR REPLACE, and their primary keys
REPLACE_KEYS = {"settings": ("key",), "days": ("install_id", "day")}


def translate(q: str, has_params: bool) -> str:
    """SQLite's dialect, as this app uses it, in Postgres's."""
    if not re.match(r"(?i)\s*(SELECT|INSERT|UPDATE|DELETE|WITH)", q):       # a schema change
        q = re.sub(r"(?i)INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", q)
        q = re.sub(r"(?i)\bINTEGER\b", "BIGINT", q)
    q = re.sub(r"(?im)^\s*PRAGMA journal_mode=WAL;\s*$", "", q)
    if m := re.match(r"(?i)\s*PRAGMA table_info\((\w+)\)\s*$", q):
        return ("SELECT ordinal_position - 1, column_name FROM information_schema.columns "
                f"WHERE table_schema = current_schema() AND table_name = '{m.group(1)}' ORDER BY ordinal_position")
    if re.match(r"(?i)\s*INSERT OR IGNORE INTO", q):
        q = re.sub(r"(?i)INSERT OR IGNORE INTO", "INSERT INTO", q, count=1) + " ON CONFLICT DO NOTHING"
    elif m := re.match(r"(?i)\s*INSERT OR REPLACE INTO (\w+) \(([^)]*)\)", q):
        table, cols = m.group(1), [c.strip() for c in m.group(2).split(",")]
        keys = REPLACE_KEYS[table]
        rest = [c for c in cols if c not in keys]
        q = re.sub(r"(?i)INSERT OR REPLACE INTO", "INSERT INTO", q, count=1) + \
            f" ON CONFLICT ({', '.join(keys)}) DO UPDATE SET " + ", ".join(f"{c} = EXCLUDED.{c}" for c in rest)
    if has_params:
        q = q.replace("%", "%%").replace("?", "%s")
    return q


class Row(tuple):
    """Like sqlite3.Row: r[0], r["code"], dict(r). Whole-number sums come back as ints, not Decimal."""

    def __new__(cls, names: list[str], values):
        r = super().__new__(cls, (int(v) if isinstance(v, Decimal) and v == v.to_integral_value()
                                  else float(v) if isinstance(v, Decimal) else v for v in values))
        r._names = names
        return r

    def __getitem__(self, k):
        return super().__getitem__(self._names.index(k) if isinstance(k, str) else k)

    def keys(self):
        return list(self._names)


def _rows(cursor):
    names = [d.name for d in cursor.description] if cursor.description else []
    return lambda values: Row(names, values)


class Conn:
    def __init__(self, pool):
        self.pool = pool

    def __enter__(self):
        self._cm = self.pool.connection()
        self.c = self._cm.__enter__()          # commits when the block ends, rolls back on an error
        return self

    def __exit__(self, *exc):
        return self._cm.__exit__(*exc)

    def execute(self, q: str, params=()):
        return self.c.execute(translate(q, bool(params)), tuple(params) or None)

    def executemany(self, q: str, seq):
        cur = self.c.cursor()
        cur.executemany(translate(q, True), [tuple(p) for p in seq])
        return cur

    def executescript(self, script: str):
        self.c.execute(translate(script, False))
        # every table here: row level security on, with no policies, so only this server's own login reaches them
        self.c.execute("""DO $$ DECLARE t text; BEGIN
            FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = current_schema() AND NOT rowsecurity LOOP
              EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
              IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
                EXECUTE format('REVOKE ALL ON %I FROM anon, authenticated', t);
              END IF;
            END LOOP; END $$""")


def pool(url: str, schema: str):
    import psycopg
    from psycopg import sql as pgsql
    from psycopg_pool import ConnectionPool

    with psycopg.connect(url, autocommit=True) as conn:        # once, before the pool's connections race to it
        conn.execute(pgsql.SQL("CREATE SCHEMA IF NOT EXISTS {}").format(pgsql.Identifier(schema)))

    def configure(conn):
        conn.execute(pgsql.SQL("SET search_path TO {}").format(pgsql.Identifier(schema)))
        conn.commit()

    return ConnectionPool(url, min_size=1, max_size=5, open=True, configure=configure, kwargs={
        "row_factory": _rows, "cursor_factory": psycopg.ClientCursor, "prepare_threshold": None})


if __name__ == "__main__":     # the translations this app relies on
    assert translate("SELECT 1 FROM x WHERE a=? AND b LIKE '5%'", True) == "SELECT 1 FROM x WHERE a=%s AND b LIKE '5%%'"
    assert translate("INSERT OR IGNORE INTO pilots (code) VALUES (?)", True).endswith("ON CONFLICT DO NOTHING")
    assert translate("INSERT OR REPLACE INTO days (install_id, day, counts) VALUES (?,?,?)", True).endswith(
        "ON CONFLICT (install_id, day) DO UPDATE SET counts = EXCLUDED.counts")
    assert "BIGINT GENERATED" in translate("CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, n INTEGER)", False)
    r = Row(["a", "b"], [1, Decimal(3)])
    assert (r[0], r["b"], dict(r), list(r)) == (1, 3, {"a": 1, "b": 3}, [1, 3])
    print("ok")
